def page(m):
    base = "../"
    title = {k: f"{m['name'][k]} — манасчы" for k in ("ky", "ru")}
    facts = "\n    ".join(f'<div class="fact"><div class="k">{t(k)}</div><div class="v">{t(v)}</div></div>'
                         for k, v in m["facts"])
    secs = []
    for i, (h, body) in enumerate(m["sections"]):
        paras = "".join(f'<p lang="ky">{escape(a)}</p>' for a in body["ky"]) + \
                "".join(f'<p lang="ru">{escape(a)}</p>' for a in body["ru"])
        secs.append(f"<h2>{t(h)}</h2>\n  {paras}")
        if i == 0 and m["quote"]:
            q, who = m["quote"]
            secs.append(f"<blockquote>{t(q)}<cite>{t(who)}</cite></blockquote>")
