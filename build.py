def cards(items, base):
    out = []
    for m in items:
        out.append(f"""<a class="card" href="{base}{m['slug']}/">
      <img src="{base}img/{m['img']}" alt="{escape(m['name']['ky'])}" loading="lazy">
      <div><b>{t(m['name'])}</b><span>{t(m['years'])} · {t(m['short'])}</span></div>
    </a>""")
    return '<div class="others">' + "\n    ".join(out) + "</div>"


